export function icon(name, size) {
  const span = document.createElement('span');
  span.style.display = 'inline-flex';
  span.innerHTML =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"${size ? ` width="${size}" height="${size}"` : ''}>${ICONS[name] || ''}</svg>`;
  return span.firstElementChild;
}

/* ------------------------------------------------------------- dates */

/** DB timestamps are UTC. If the string has no zone, treat it as UTC. */
export function parseTs(ts) {
  if (!ts) return null;
  let s = String(ts).trim().replace(' ', 'T');
  if (!/(Z|[+-]\d{2}:?\d{2})$/.test(s)) s += 'Z';
  const d = new Date(s);
  return Number.isNaN(d.getTime()) ? null : d;
}

export function fmtDateTime(ts) {
  const d = ts instanceof Date ? ts : parseTs(ts);
  if (!d) return '-';
  return d.toLocaleString(undefined, { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' });
}

export function fmtDate(ts) {
  const d = ts instanceof Date ? ts : parseTs(ts);
  if (!d) return '-';
  return d.toLocaleDateString(undefined, { day: 'numeric', month: 'short', year: 'numeric' });
}

export function fmtShort(ts) {
  const d = ts instanceof Date ? ts : parseTs(ts);
  if (!d) return '-';
  return d.toLocaleDateString(undefined, { day: 'numeric', month: 'short' });
}

/** Value for <input type="datetime-local"> in local time. */
export function toLocalInput(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}T${p(date.getHours())}:${p(date.getMinutes())}`;
}

export const fmtPct = (v) => (v == null ? '-' : `${Math.round(v)}%`);

export function pctClass(v, target = 75) {
  if (v == null) return 'mute';
  if (v >= target) return 'ok';
  if (v >= target - 15) return 'warn';
  return 'bad';
}

/* ------------------------------------------------------------- files */

export function download(filename, text, mime = 'text/csv;charset=utf-8') {
  const blob = new Blob(['\ufeff', text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = h('a', { href: url, download: filename });
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function csvCell(v) {
  const s = v == null ? '' : String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function toCsv(rows) {
  return rows.map((r) => r.map(csvCell).join(',')).join('\r\n');
}

export function slug(s) {
  return String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'attendance';
}

/* ------------------------------------------------------------- storage */
export const store = {
  get(key, fallback = null) {
    try {
      const v = localStorage.getItem(key);
      return v === null ? fallback : JSON.parse(v);
    } catch (_) {
      return fallback;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(key, JSON.stringify(value));
    } catch (_) { /* private mode: ignore */ }
  },
  del(key) {
    try {
      localStorage.removeItem(key);
    } catch (_) { /* ignore */ }
  },
};

/** Load an image File/Blob into an HTMLImageElement. */
export function loadImage(fileOrBlob) {
  return new Promise((resolve, reject) => {
    const url = URL.createObjectURL(fileOrBlob);
    const img = new Image();
    img.onload = () => {
      URL.revokeObjectURL(url);
      resolve(img);
    };
    img.onerror = () => {
      URL.revokeObjectURL(url);
      reject(new Error('Could not read this image.'));
    };
    img.src = url;
  });
}
