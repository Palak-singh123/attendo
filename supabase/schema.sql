-- =====================================================================
--  Attendo - Supabase setup  (safe to run more than once)
--  Supabase dashboard -> SQL Editor -> New query -> paste -> Run
--
--  * Already have the old Streamlit tables?  This only ADDS what is missing.
--    Your teachers, subjects, enrollments and attendance history stay as they are.
--  * Fresh project?  This creates everything.
-- =====================================================================

create table if not exists teachers (
  teacher_id  bigint generated by default as identity primary key,
  username    text not null unique,
  password    text not null,
  name        text not null,
  created_at  timestamptz default now()
);

create table if not exists students (
  student_id       bigint generated by default as identity primary key,
  name             text not null,
  face_embedding   jsonb,   -- legacy (Python / InsightFace). No longer used.
  voice_embedding  jsonb,   -- legacy (Python / Resemblyzer). No longer used.
  created_at       timestamptz default now()
);

-- NEW: 128-number face descriptors made in the browser (face-api.js).
-- Stores a few samples per student, e.g. [[...128 numbers...], [...], [...]]
alter table students add column if not exists face_descriptor jsonb;

create table if not exists subjects (
  subject_id    bigint generated by default as identity primary key,
  subject_code  text not null,
  name          text not null,
  section       text not null,
  teacher_id    bigint references teachers(teacher_id) on delete cascade,
  created_at    timestamptz default now()
);

create table if not exists subject_students (
  student_id  bigint references students(student_id) on delete cascade,
  subject_id  bigint references subjects(subject_id) on delete cascade,
  created_at  timestamptz default now()
);

create table if not exists attendance_logs (
  student_id  bigint references students(student_id) on delete cascade,
  subject_id  bigint references subjects(subject_id) on delete cascade,
  "timestamp" timestamp not null,
  is_present  boolean not null default false
);

-- Speed-ups (optional). Each one is skipped quietly if it cannot be created.
do $$
begin
  begin create index if not exists attendance_logs_subject_ts_idx on attendance_logs (subject_id, "timestamp");
  exception when others then raise notice 'Skipped index: %', sqlerrm; end;
  begin create index if not exists attendance_logs_student_idx on attendance_logs (student_id);
  exception when others then raise notice 'Skipped index: %', sqlerrm; end;
  begin create index if not exists subject_students_subject_idx on subject_students (subject_id);
  exception when others then raise notice 'Skipped index: %', sqlerrm; end;
  begin create index if not exists subject_students_student_idx on subject_students (student_id);
  exception when others then raise notice 'Skipped index: %', sqlerrm; end;
end $$;

-- One subject code = one subject (case-insensitive). Skipped quietly if old data has duplicates.
do $$
begin
  create unique index if not exists subjects_code_upper_idx on subjects (upper(subject_code));
exception when others then
  raise notice 'Skipped unique subject-code index: %', sqlerrm;
end $$;

